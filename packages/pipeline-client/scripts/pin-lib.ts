import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { z } from 'zod';

const PACKAGE_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** Files the pin owns, relative to packages/pipeline-client. */
export const PIN_FILE = resolve(PACKAGE_DIR, 'openapi.pin.json');
export const SNAPSHOT_FILE = resolve(PACKAGE_DIR, 'openapi/openapi.json');
export const GENERATED_FILE = resolve(PACKAGE_DIR, 'src/generated/pipeline-api.ts');

const hex = (length: number) => z.string().regex(new RegExp(`^[0-9a-f]{${String(length)}}$`));

export const PinSchema = z
  .object({
    $comment: z.string().optional(),
    repository: z.url({ protocol: /^https$/ }),
    contractFrozenAt: z.string().regex(/^[0-9a-f]{7,40}$/),
    commit: hex(40).nullable(),
    path: z
      .string()
      .min(1)
      .refine((value) => !value.startsWith('/') && !value.split('/').includes('..'), {
        message: 'path must be relative to the repository root',
      })
      .nullable(),
    sha256: hex(64).nullable(),
  })
  .refine(
    (pin) =>
      [pin.commit, pin.path, pin.sha256].every((value) => value === null) ||
      [pin.commit, pin.path, pin.sha256].every((value) => value !== null),
    { message: 'commit, path and sha256 are set together or are all null (pending)' },
  );

export type Pin = z.infer<typeof PinSchema>;
export type SetPin = Pin & { commit: string; path: string; sha256: string };

export function parsePin(text: string): Pin {
  return PinSchema.parse(JSON.parse(text));
}

export function readPin(): Pin {
  return parsePin(readFileSync(PIN_FILE, 'utf8'));
}

export function isPinSet(pin: Pin): pin is SetPin {
  return pin.commit !== null && pin.path !== null && pin.sha256 !== null;
}

export function sha256Hex(bytes: Uint8Array): string {
  return createHash('sha256').update(bytes).digest('hex');
}

/** The spec must be OpenAPI 3.1 JSON, as the contract states. Returns the parsed document. */
export function assertOpenApi31(bytes: Uint8Array): Record<string, unknown> {
  const document: unknown = JSON.parse(Buffer.from(bytes).toString('utf8'));
  if (typeof document !== 'object' || document === null || Array.isArray(document)) {
    throw new Error('openapi.json is not a JSON object');
  }
  const version = (document as Record<string, unknown>).openapi;
  if (typeof version !== 'string' || !version.startsWith('3.1')) {
    throw new Error(`expected OpenAPI 3.1, found ${JSON.stringify(version)}`);
  }
  return document as Record<string, unknown>;
}

/** `https://github.com/<owner>/<repo>` -> the raw URL of `path` at `commit`. */
export function rawGithubUrl(repository: string, commit: string, path: string): string {
  const match = /^https:\/\/github\.com\/([^/]+)\/([^/]+?)(?:\.git)?\/?$/.exec(repository);
  if (!match?.[1] || !match[2]) throw new Error(`not a GitHub repository URL: ${repository}`);
  const encodedPath = path.split('/').map(encodeURIComponent).join('/');
  return `https://raw.githubusercontent.com/${match[1]}/${match[2]}/${commit}/${encodedPath}`;
}

/** The header every generated file starts with, so a reader can trace it to the pinned bytes. */
export function generatedBanner(pin: SetPin): string {
  return [
    '// Generated by openapi-typescript from the pinned pipeline contract. Do not edit.',
    `// Source: ${pin.repository} at ${pin.commit}, ${pin.path} (sha256 ${pin.sha256}).`,
    '// Regenerate: pnpm --filter @roofing-crm/pipeline-client generate',
    '',
  ].join('\n');
}

/** Renders the TypeScript types for the pinned spec. */
export async function renderTypes(specBytes: Uint8Array, pin: SetPin): Promise<string> {
  const { default: openapiTS, astToString } = await import('openapi-typescript');
  const ast = await openapiTS(Buffer.from(specBytes).toString('utf8'));
  return `${generatedBanner(pin)}\n${astToString(ast)}`;
}
